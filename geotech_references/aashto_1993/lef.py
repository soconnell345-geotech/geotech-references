def _interp1d(x, xs, ys):
    """Linear interpolation of ys(xs) at x; x is assumed already clamped
    into [xs[0], xs[-1]] by the caller."""
    if x <= xs[0]:
        return ys[0]
    if x >= xs[-1]:
        return ys[-1]
    i = bisect.bisect_right(xs, x) - 1
    x0, x1 = xs[i], xs[i + 1]
    if x1 == x0:
        return ys[i]
    y0, y1 = ys[i], ys[i + 1]
    t = (x - x0) / (x1 - x0)
    return y0 + t * (y1 - y0)


def _lookup(table, axle_load_kips, col_value, col_name):
    """Bilinear interpolation: first across the printed columns (SN or D)
    for every printed load row, then across the printed load rows.
    Returns (lef, notes)."""
    loads = table["loads"]
    columns = table["columns"]
    rows = table["rows"]
    notes = []

    load = axle_load_kips
    if load < loads[0] or load > loads[-1]:
        clamped = min(max(load, loads[0]), loads[-1])
        notes.append(
            f"axle_load_kips={axle_load_kips:g} is outside the printed "
            f"table range [{loads[0]}, {loads[-1]}] kips; clamped to "
            f"{clamped:g}."
        )
        load = clamped

    col = col_value
    if col < columns[0] or col > columns[-1]:
        clamped = min(max(col, columns[0]), columns[-1])
        notes.append(
            f"{col_name}={col_value:g} is outside the printed table range "
            f"[{columns[0]}, {columns[-1]}]; clamped to {clamped:g}."
        )
        col = clamped

    col_values_per_load = [_interp1d(col, columns, row) for row in rows]
    lef = _interp1d(load, loads, col_values_per_load)
    return lef, notes


def load_equivalency_factor(pavement_type, axle_config, axle_load_kips,
                            sn=None, d_in=None, pt=2.5) -> dict:
    """Axle load equivalency factor (LEF), bilinear interpolation over the
    full printed Appendix D table grid (Tables D.1-D.18).

    See the module docstring for why this is table interpolation rather
    than a closed-form equation (the closed-form AASHO Road Test equations
    are in "Appendix MM of Volume 2", not in ``docs/aashto1993.pdf``).

    Parameters
    ----------
    pavement_type : str
        'flexible' or 'rigid'.
    axle_config : str
        'single', 'tandem', or 'triple'.
    axle_load_kips : float
        Axle (group) load, kips, > 0. Single-axle tables are printed for
        2-50 kips; tandem/triple tables for 2-90 kips. Loads outside the
        printed range are clamped to the nearest endpoint (see 'note').
    sn : float, optional
        Pavement structural number (flexible only), required when
        pavement_type='flexible'. Printed columns are SN=1-6; values
        outside that range are clamped (see 'note').
    d_in : float, optional
        PCC slab thickness, inches (rigid only), required when
        pavement_type='rigid'. Printed columns are D=6-14 in; values
        outside that range are clamped (see 'note').
    pt : float, optional
        Terminal serviceability index. Must be EXACTLY 2.0, 2.5, or 3.0
        (the only values printed in Appendix D) -- default 2.5.
        Interpolating between serviceability levels is not supported.

    Returns
    -------
    dict
        {'pavement_type', 'axle_config', 'axle_load_kips', 'pt',
         'sn' or 'd_in', 'lef', 'table', 'reference', 'note'?}.
        'note' is present only when a load/sn/d_in fell outside the
        printed range and was clamped.

    Raises
    ------
    ValueError
        If pavement_type/axle_config is unrecognized, pt is not exactly
        one of 2.0/2.5/3.0, axle_load_kips <= 0, sn/d_in is missing or
        <= 0 for the given pavement_type, or the wrong one of sn/d_in is
        supplied for the given pavement_type.
    """
    pavement_key = str(pavement_type).strip().lower()
    if pavement_key not in ("flexible", "rigid"):
        raise ValueError(
            f"pavement_type must be 'flexible' or 'rigid', got '{pavement_type}'"
        )
    axle_key = str(axle_config).strip().lower()
    if axle_key not in ("single", "tandem", "triple"):
        raise ValueError(
            f"axle_config must be 'single', 'tandem', or 'triple', got "
            f"'{axle_config}'"
        )
    if axle_load_kips <= 0:
        raise ValueError(f"axle_load_kips must be > 0, got {axle_load_kips}")

    pt_key = None
    for p in (2.0, 2.5, 3.0):
        if abs(pt - p) < 1e-9:
            pt_key = p
            break
    if pt_key is None:
        raise ValueError(
            f"pt must be exactly one of 2.0, 2.5, 3.0 (the only terminal "
            f"serviceability values printed in Appendix D); interpolating "
            f"between pt values is not supported. Got {pt}."
        )

    if pavement_key == "flexible":
        if d_in is not None:
            raise ValueError(
                "d_in is not applicable to flexible pavements; use sn"
            )
        if sn is None:
            raise ValueError(
                "flexible pavement requires sn (pavement structural number)"
            )
        if sn <= 0:
            raise ValueError(f"sn must be > 0, got {sn}")
        col_value, col_name = sn, "sn"
    else:
        if sn is not None:
            raise ValueError(
                "sn is not applicable to rigid pavements; use d_in"
            )
        if d_in is None:
            raise ValueError(
                "rigid pavement requires d_in (slab thickness, inches)"
            )
        if d_in <= 0:
            raise ValueError(f"d_in must be > 0, got {d_in}")
        col_value, col_name = d_in, "d_in"

    table = _TABLES[(pavement_key, axle_key, pt_key)]
    lef, notes = _lookup(table, axle_load_kips, col_value, col_name)

    out = {
        "pavement_type": pavement_key,
        "axle_config": axle_key,
        "axle_load_kips": axle_load_kips,
        "pt": pt_key,
        "lef": round(lef, 4),
        "table": f"Table D.{table['table_num']}",
        "reference": (
            f"AASHTO 1993 Guide, Table D.{table['table_num']} "
            f"(pdf_page {table['pdf_page']}, printed {table['printed_page']})"
        ),
    }
    if pavement_key == "flexible":
        out["sn"] = sn
    else:
        out["d_in"] = d_in
    if notes:
        out["note"] = " ".join(notes)
    return out
