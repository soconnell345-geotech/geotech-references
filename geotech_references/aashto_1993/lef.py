"""AASHTO Guide for Design of Pavement Structures (1993) -- axle load
equivalency factors (LEF), full Appendix D table digitization.

PROVENANCE NOTE (read this first): Appendix D's own introduction states that
the closed-form AASHO Road Test equations used to derive the printed LEF
tables are NOT in this Guide -- "Appendix MM of Volume 2 presents the AASHO
Road Test-based equations that were used to generate these tables. It also
provides some support for extending the tables to tridem axle loadings."
(pdf_page 361, printed D-2). ``docs/aashto1993.pdf`` is Volume 1 only (its own
front-matter Appendices list, pdf_page 19 printed xvii, runs A through N with
no Volume 2 / Appendix MM content); the full extent of Appendix D (pdf_page
360-384, printed D-1 through D-25) was read page-by-page to confirm no
equation is printed anywhere in it. So this module implements the axle load
equivalency factor as BILINEAR INTERPOLATION directly over the full printed
table grid (Tables D.1-D.18) rather than a closed-form equation -- every
number below is transcribed from a specific rendered page of
``docs/aashto1993.pdf``, never from memory of the classic AASHO Gt/Bx
formula.

Table layout (all 18 tables share the same page arithmetic): Table D.N is at
pdf_page 361+N (0-based fitz index), printed page D-(N+2). Table numbering
(confirmed against each table's own printed caption, not assumed):

    pt=2.0: D.1  D.2  D.3  (flexible single/tandem/triple)
            D.10 D.11 D.12 (rigid    single/tandem/triple)
    pt=2.5: D.4  D.5  D.6  (flexible single/tandem/triple)
            D.13 D.14 D.15 (rigid    single/tandem/triple)
    pt=3.0: D.7  D.8  D.9  (flexible single/tandem/triple)
            D.16 D.17 D.18 (rigid    single/tandem/triple)

Flexible columns are pavement structural number SN = 1..6; rigid columns are
slab thickness D = 6..14 inches. Single/flexible-pt2.5 (Table D.4) and
single/tandem-rigid-pt2.5 (Tables D.13/D.14) were cross-validated to exact
agreement against the independently-digitized SN=5 / D=9 curves already in
``tables.py`` (``esal_flexible_single_axle``/``esal_flexible_tandem_axle``/
``esal_rigid_single_axle``/``esal_rigid_tandem_axle``), which gives high
confidence in the decimal-placement convention used throughout (the printed
tables give 3 significant figures with the decimal point rendered as a small
gap in the scan, sometimes visible as an actual "." character; magnitude
class -- not digit count alone -- fixes the decimal position, e.g. "165" at
a load of 12 kips is 0.165, while "165" later in the same column at a load of
86 kips would be 165 -- deduced independently from column monotonicity and
the defining anchor that every SINGLE-axle table reads exactly 1.00 at the
18-kip row, then cross-checked against the pre-existing digitization above).

Every printed table cell was read from a >=200 dpi render and re-verified in
a second independent pass; the only unreadable cell found is documented
below (Table D.12, load=74 kips, D=9 in): a scan defect (a smudge in place of
a digit, confirmed unreadable even at a 600 dpi crop). Its value here (15.8)
is a linear interpolation between the printed D=8in (15.4) and D=10in (16.2)
neighbors at the same load, NOT a transcribed printed value.

UNITS: US customary, per the guide (axle load in kips; SN dimensionless;
slab thickness D in inches). LEF itself is dimensionless.

Interpolation policy
---------------------
- Axle load: linear interpolation between the printed load rows; loads
  outside the printed range are CLAMPED to the nearest printed endpoint
  (with a ``note`` in the returned dict).
- SN (flexible) / D (rigid): linear interpolation between the printed
  columns; values outside the printed column range are CLAMPED to the
  nearest printed endpoint (with a ``note``).
- Terminal serviceability pt: EXACT match only, one of 2.0, 2.5, 3.0 (the
  only three values printed in Appendix D). Interpolating between
  serviceability levels is not physically well-posed from table data alone
  (it is not simply linear) and the Guide does not sanction it, so an
  off-grid pt raises ``ValueError`` rather than silently interpolating.
"""

